"""PostgreSQL storage for the RelayGuard synthetic action flow.

The demonstration keeps the synthetic side effect and idempotency record in one
PostgreSQL transaction. This atomic boundary demonstrates the local database pattern;
it does not guarantee exactly-once delivery across arbitrary external network services.
"""
from __future__ import annotations

import logging
from typing import Any
from urllib.parse import urlsplit, urlunsplit

import psycopg
from psycopg.rows import dict_row

from app.config import get_database_url

logger = logging.getLogger("relayguard.storage")


def mask_database_url(url: str) -> str:
    """Mask password credentials in a database connection URL for safe diagnostics."""
    try:
        parsed = urlsplit(url)
        if parsed.password is not None:
            user = parsed.username or ""
            host = parsed.hostname or ""
            port = f":{parsed.port}" if parsed.port else ""
            netloc = f"{user}:***@{host}{port}"
            return urlunsplit((parsed.scheme, netloc, parsed.path, parsed.query, parsed.fragment))
        return url
    except Exception:
        return "postgresql://***:***@***"


def connect(db_url: str | None = None) -> psycopg.Connection[dict[str, Any]]:
    """Open a PostgreSQL connection using Psycopg 3 with dict_row factory.

    Raises psycopg.OperationalError with sanitized error text if connection fails,
    ensuring credentials and passwords are never exposed.
    """
    resolved_url = db_url or get_database_url()
    try:
        connection = psycopg.connect(
            resolved_url,
            row_factory=dict_row,
            autocommit=False,
            connect_timeout=5,
        )
        return connection
    except psycopg.OperationalError:
        masked = mask_database_url(resolved_url)
        logger.error("Failed to connect to PostgreSQL database at '%s'", masked)
        raise psycopg.OperationalError(
            f"Could not connect to PostgreSQL at '{masked}'. "
            "Ensure the database service is running and accessible."
        ) from None


def initialize_database(db_url: str | None = None) -> None:
    """Deterministic schema initialization for RelayGuard.

    Safe to run repeatedly on startup or test setup. Creates:
    - `actions`: idempotency ledger tracking canonical payload hashes and stored results.
    - `effects`: synthetic tool execution effects with foreign key and unique constraint.
    - `baseline_effects`: intentionally unconstrained table used ONLY to reproduce the defect.
    """
    conn = connect(db_url)
    try:
        with conn.transaction():
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS actions (
                    idempotency_key TEXT PRIMARY KEY,
                    payload_hash TEXT NOT NULL,
                    result_json JSONB NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
                );

                CREATE TABLE IF NOT EXISTS effects (
                    effect_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    idempotency_key TEXT NOT NULL UNIQUE REFERENCES actions(idempotency_key),
                    action_type TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
                );

                -- INTENTIONALLY DEFECTIVE BASELINE TABLE:
                -- Has no unique constraint on idempotency_key to reproduce duplicate side effects.
                CREATE TABLE IF NOT EXISTS baseline_effects (
                    effect_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    idempotency_key TEXT NOT NULL,
                    action_type TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
                );
                """
            )
    finally:
        if not conn.closed:
            conn.close()


def truncate_tables(db_url: str | None = None) -> None:
    """Helper to safely truncate tables for clean test repeatability."""
    conn = connect(db_url)
    try:
        with conn.transaction():
            conn.execute("TRUNCATE TABLE effects, actions, baseline_effects RESTART IDENTITY CASCADE;")
    finally:
        if not conn.closed:
            conn.close()
